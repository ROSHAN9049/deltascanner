BEGIN;

CREATE TABLE IF NOT EXISTS public.dd_paper_trades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trade_key TEXT NOT NULL UNIQUE,
  symbol TEXT NOT NULL,
  underlying TEXT NULL,
  strategy TEXT NOT NULL CHECK (strategy IN ('OPTIONS_BUY')),
  side TEXT NOT NULL CHECK (side = 'BUY'),
  option_type TEXT NOT NULL CHECK (option_type IN ('CALL', 'PUT')),
  strike NUMERIC NULL,
  expiry_at TIMESTAMPTZ NULL,
  qty NUMERIC NOT NULL CHECK (qty > 0),
  entry_price NUMERIC NOT NULL CHECK (entry_price > 0),
  current_price NUMERIC NULL,
  exit_price NUMERIC NULL,
  stop_price NUMERIC NULL,
  take_profit_price NUMERIC NULL,
  unrealized_pnl NUMERIC NOT NULL DEFAULT 0,
  realized_pnl NUMERIC NULL,
  status TEXT NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'CLOSED')),
  fill_type TEXT NOT NULL DEFAULT 'SIMULATED_FILL' CHECK (fill_type = 'SIMULATED_FILL'),
  source TEXT NOT NULL DEFAULT 'DELTA_INDIA_LIVE_PUBLIC',
  exit_reason TEXT NULL,
  opened_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  closed_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  raw JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS dd_paper_trades_status_opened_idx
  ON public.dd_paper_trades (status, opened_at DESC);
CREATE INDEX IF NOT EXISTS dd_paper_trades_symbol_status_idx
  ON public.dd_paper_trades (symbol, status);

ALTER TABLE public.dd_paper_trades ENABLE ROW LEVEL SECURITY;

NOTIFY pgrst, 'reload schema';
COMMIT;
