BEGIN;

CREATE TABLE IF NOT EXISTS public.dd_delta_positions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id TEXT NULL,
  client_order_id TEXT NULL,
  product_id INTEGER NULL,
  symbol TEXT NOT NULL,
  side TEXT NOT NULL CHECK (side IN ('BUY', 'SELL')),
  qty NUMERIC NOT NULL DEFAULT 0 CHECK (qty >= 0),
  entry_price NUMERIC NULL,
  current_price NUMERIC NULL,
  unrealized_pnl NUMERIC NULL,
  realized_pnl NUMERIC NULL,
  sl_price NUMERIC NULL,
  tp_price NUMERIC NULL,
  status TEXT NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'CLOSED')),
  strategy TEXT NOT NULL DEFAULT 'MOMENTUM' CHECK (strategy IN ('MOMENTUM', 'SCALPING', 'GRID')),
  opened_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  closed_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS dd_delta_positions_one_open_symbol_idx
  ON public.dd_delta_positions (symbol)
  WHERE status = 'OPEN';
CREATE INDEX IF NOT EXISTS dd_delta_positions_status_updated_idx
  ON public.dd_delta_positions (status, updated_at DESC);
CREATE INDEX IF NOT EXISTS dd_delta_positions_symbol_opened_idx
  ON public.dd_delta_positions (symbol, opened_at DESC);
CREATE INDEX IF NOT EXISTS dd_delta_positions_closed_idx
  ON public.dd_delta_positions (closed_at DESC)
  WHERE status = 'CLOSED';

ALTER TABLE public.dd_delta_positions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.dd_delta_positions FROM anon, authenticated;
GRANT ALL ON TABLE public.dd_delta_positions TO service_role;
GRANT USAGE, SELECT, UPDATE ON SEQUENCE public.dd_delta_positions_id_seq TO service_role;

NOTIFY pgrst, 'reload schema';
COMMIT;
