BEGIN;

ALTER TABLE public.dd_option_cache
  ADD COLUMN IF NOT EXISTS iv_current NUMERIC NULL;

CREATE TABLE IF NOT EXISTS public.dd_iv_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  symbol TEXT NOT NULL,
  underlying TEXT NOT NULL,
  iv_current NUMERIC NOT NULL CHECK (iv_current > 0 AND iv_current <= 500),
  observed_at TIMESTAMPTZ NOT NULL,
  source TEXT NOT NULL DEFAULT 'delta_public_option_ticker',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS dd_iv_history_symbol_observed_idx
  ON public.dd_iv_history (symbol, observed_at DESC);

ALTER TABLE public.dd_iv_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.dd_iv_history FROM anon, authenticated;
GRANT ALL ON TABLE public.dd_iv_history TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.dd_iv_history_id_seq TO service_role;

ALTER TABLE public.dd_option_positions
  ADD COLUMN IF NOT EXISTS delta_position_id BIGINT NULL
    REFERENCES public.dd_delta_positions(id) ON DELETE SET NULL;

ALTER TABLE public.dd_delta_positions
  ADD COLUMN IF NOT EXISTS exit_price NUMERIC NULL,
  ADD COLUMN IF NOT EXISTS close_reason TEXT NULL;

ALTER TABLE public.dd_delta_positions
  DROP CONSTRAINT IF EXISTS dd_delta_positions_strategy_check;
ALTER TABLE public.dd_delta_positions
  ADD CONSTRAINT dd_delta_positions_strategy_check
  CHECK (strategy IN ('MOMENTUM', 'SCALPING', 'GRID', 'OPTIONS_BUY', 'OPTIONS_SELL')) NOT VALID;
ALTER TABLE public.dd_delta_positions
  VALIDATE CONSTRAINT dd_delta_positions_strategy_check;

COMMENT ON TABLE public.dd_iv_history IS
  'Private rolling 30-day option implied-volatility observations. Entries require at least seven days of history.';
COMMENT ON COLUMN public.dd_delta_positions.exit_price IS
  'Verified average exit premium for canonical Delta Options position lifecycle rows.';
COMMENT ON COLUMN public.dd_delta_positions.close_reason IS
  'Normalized Options exit classification: TP, SL, or TIME_EXIT.';

NOTIFY pgrst, 'reload schema';
COMMIT;
