CREATE OR REPLACE FUNCTION public.record_dd_options_execution_fill(
  p_order_attempt_id BIGINT,
  p_exchange_fill_id TEXT,
  p_fill_qty NUMERIC,
  p_fill_price NUMERIC,
  p_commission NUMERIC,
  p_commission_currency TEXT,
  p_filled_at TIMESTAMPTZ,
  p_raw JSONB DEFAULT '{}'::JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $
DECLARE
  v_order public.dd_options_execution_orders%ROWTYPE;
  v_fill_id BIGINT;
  v_existing_order_attempt_id BIGINT;
  v_total_qty NUMERIC;
  v_average_price NUMERIC;
  v_total_commission NUMERIC;
  v_commission_currency TEXT;
  v_currency_count INTEGER;
  v_leg_entry_qty NUMERIC;
  v_leg_entry_avg NUMERIC;
  v_leg_entry_commission NUMERIC;
  v_leg_entry_currency TEXT;
  v_leg_entry_currency_count INTEGER;
  v_leg_exit_qty NUMERIC;
  v_leg_exit_avg NUMERIC;
  v_leg_exit_commission NUMERIC;
  v_leg_exit_currency TEXT;
  v_leg_exit_currency_count INTEGER;
  v_reconciliation_required BOOLEAN := FALSE;
BEGIN
  IF p_order_attempt_id IS NULL OR
     NULLIF(BTRIM(p_exchange_fill_id), '') IS NULL OR
     p_fill_qty IS NULL OR p_fill_qty <= 0 OR
     p_fill_price IS NULL OR p_fill_price <= 0 OR
     p_filled_at IS NULL OR
     (p_commission IS NOT NULL AND NULLIF(BTRIM(p_commission_currency), '') IS NULL) THEN
    RAISE EXCEPTION 'Options fill data is invalid or incomplete';
  END IF;

  SELECT * INTO v_order
  FROM public.dd_options_execution_orders
  WHERE id = p_order_attempt_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Options fill references an unknown order attempt';
  END IF;

  INSERT INTO public.dd_options_execution_fills (
    order_attempt_id, group_id, leg_id, exchange_fill_id, exchange_order_id,
    client_order_id, symbol, intent, side, fill_qty, fill_price, commission,
    commission_currency, filled_at, raw
  ) VALUES (
    v_order.id, v_order.group_id, v_order.leg_id, p_exchange_fill_id,
    v_order.exchange_order_id, v_order.client_order_id, v_order.symbol,
    v_order.intent, v_order.side, p_fill_qty, p_fill_price, p_commission,
    NULLIF(UPPER(BTRIM(p_commission_currency)), ''), p_filled_at,
    COALESCE(p_raw, '{}'::JSONB)
  )
  ON CONFLICT (exchange_fill_id) DO NOTHING
  RETURNING id INTO v_fill_id;

  IF v_fill_id IS NULL THEN
    SELECT order_attempt_id INTO v_existing_order_attempt_id
    FROM public.dd_options_execution_fills
    WHERE exchange_fill_id = p_exchange_fill_id;

    IF v_existing_order_attempt_id IS DISTINCT FROM v_order.id THEN
      UPDATE public.dd_options_execution_groups
      SET state = 'RECONCILIATION_REQUIRED',
          last_error_code = 'OPTIONS_FILL_ID_COLLISION',
          last_error_detail = 'An exchange fill ID was replayed against a different order attempt',
          updated_at = NOW()
      WHERE id IN (
        v_order.group_id,
        (SELECT group_id FROM public.dd_options_execution_fills WHERE exchange_fill_id = p_exchange_fill_id)
      );
      RETURN jsonb_build_object(
        'duplicate', false,
        'collision', true,
        'reconciliation_required', true,
        'order_attempt_id', v_order.id,
        'exchange_fill_id', p_exchange_fill_id
      );
    END IF;

    RETURN jsonb_build_object(
      'duplicate', true,
      'order_attempt_id', v_order.id,
      'exchange_fill_id', p_exchange_fill_id
    );
  END IF;

  SELECT
    COALESCE(SUM(fill_qty), 0),
    CASE WHEN SUM(fill_qty) > 0
      THEN SUM(fill_qty * fill_price) / SUM(fill_qty)
      ELSE NULL END,
    CASE WHEN COUNT(*) > 0
          AND COUNT(commission) = COUNT(*)
          AND COUNT(DISTINCT commission_currency) = 1
      THEN SUM(commission)
      ELSE NULL END,
    COUNT(DISTINCT commission_currency),
    CASE WHEN COUNT(*) > 0
          AND COUNT(commission) = COUNT(*)
          AND COUNT(DISTINCT commission_currency) = 1
      THEN MIN(commission_currency)
      ELSE NULL END
  INTO v_total_qty, v_average_price, v_total_commission, v_currency_count, v_commission_currency
  FROM public.dd_options_execution_fills
  WHERE order_attempt_id = v_order.id;

  -- The exchange order acknowledgement can be observed before later fills.
  -- Actual fills are authoritative; do not compare a newer fill total to a stale
  -- acknowledged_filled_qty value. Only requested size and fee currency conflicts
  -- can make this fill aggregation irreconcilable.
  IF v_total_qty > v_order.requested_qty OR
     v_currency_count > 1 THEN
    v_reconciliation_required := TRUE;
  END IF;

  UPDATE public.dd_options_execution_orders
  SET filled_qty = v_total_qty,
      average_fill_price = v_average_price,
      commission = v_total_commission,
      commission_currency = v_commission_currency,
      order_state = CASE
        WHEN v_reconciliation_required THEN 'RECONCILIATION_REQUIRED'
        WHEN v_total_qty >= requested_qty THEN 'FILLED'
        WHEN order_state IN ('CANCELLED', 'REJECTED', 'UNKNOWN', 'RECONCILIATION_REQUIRED') THEN order_state
        WHEN v_total_qty > 0 THEN 'PARTIALLY_FILLED'
        ELSE order_state
      END,
      updated_at = NOW()
  WHERE id = v_order.id;

  SELECT
    COALESCE(SUM(CASE WHEN o.intent = 'ENTRY' THEN f.fill_qty ELSE 0 END), 0),
    CASE WHEN SUM(CASE WHEN o.intent = 'ENTRY' THEN f.fill_qty ELSE 0 END) > 0
      THEN SUM(CASE WHEN o.intent = 'ENTRY' THEN f.fill_qty * f.fill_price ELSE 0 END) /
        SUM(CASE WHEN o.intent = 'ENTRY' THEN f.fill_qty ELSE 0 END)
      ELSE NULL END,
    CASE
      WHEN COUNT(f.exchange_fill_id) FILTER (WHERE o.intent = 'ENTRY') > 0
       AND COUNT(f.commission) FILTER (WHERE o.intent = 'ENTRY') =
           COUNT(f.exchange_fill_id) FILTER (WHERE o.intent = 'ENTRY')
       AND COUNT(DISTINCT f.commission_currency) FILTER (WHERE o.intent = 'ENTRY') = 1
      THEN SUM(f.commission) FILTER (WHERE o.intent = 'ENTRY')
      ELSE NULL
    END,
    COUNT(DISTINCT f.commission_currency) FILTER (WHERE o.intent = 'ENTRY'),
    CASE
      WHEN COUNT(f.exchange_fill_id) FILTER (WHERE o.intent = 'ENTRY') > 0
       AND COUNT(f.commission) FILTER (WHERE o.intent = 'ENTRY') =
           COUNT(f.exchange_fill_id) FILTER (WHERE o.intent = 'ENTRY')
       AND COUNT(DISTINCT f.commission_currency) FILTER (WHERE o.intent = 'ENTRY') = 1
      THEN MIN(f.commission_currency) FILTER (WHERE o.intent = 'ENTRY')
      ELSE NULL
    END,
    COALESCE(SUM(CASE WHEN o.intent IN ('EXIT', 'UNWIND') THEN f.fill_qty ELSE 0 END), 0),
    CASE WHEN SUM(CASE WHEN o.intent IN ('EXIT', 'UNWIND') THEN f.fill_qty ELSE 0 END) > 0
      THEN SUM(CASE WHEN o.intent IN ('EXIT', 'UNWIND') THEN f.fill_qty * f.fill_price ELSE 0 END) /
        SUM(CASE WHEN o.intent IN ('EXIT', 'UNWIND') THEN f.fill_qty ELSE 0 END)
      ELSE NULL END,
    CASE
      WHEN COUNT(f.exchange_fill_id) FILTER (WHERE o.intent IN ('EXIT', 'UNWIND')) > 0
       AND COUNT(f.commission) FILTER (WHERE o.intent IN ('EXIT', 'UNWIND')) =
           COUNT(f.exchange_fill_id) FILTER (WHERE o.intent IN ('EXIT', 'UNWIND'))
       AND COUNT(DISTINCT f.commission_currency) FILTER (WHERE o.intent IN ('EXIT', 'UNWIND')) = 1
      THEN SUM(f.commission) FILTER (WHERE o.intent IN ('EXIT', 'UNWIND'))
      ELSE NULL
    END,
    COUNT(DISTINCT f.commission_currency) FILTER (WHERE o.intent IN ('EXIT', 'UNWIND')),
    CASE
      WHEN COUNT(f.exchange_fill_id) FILTER (WHERE o.intent IN ('EXIT', 'UNWIND')) > 0
       AND COUNT(f.commission) FILTER (WHERE o.intent IN ('EXIT', 'UNWIND')) =
           COUNT(f.exchange_fill_id) FILTER (WHERE o.intent IN ('EXIT', 'UNWIND'))
       AND COUNT(DISTINCT f.commission_currency) FILTER (WHERE o.intent IN ('EXIT', 'UNWIND')) = 1
      THEN MIN(f.commission_currency) FILTER (WHERE o.intent IN ('EXIT', 'UNWIND'))
      ELSE NULL
    END
  INTO v_leg_entry_qty, v_leg_entry_avg, v_leg_entry_commission, v_leg_entry_currency_count,
       v_leg_entry_currency, v_leg_exit_qty, v_leg_exit_avg, v_leg_exit_commission,
       v_leg_exit_currency_count, v_leg_exit_currency
  FROM public.dd_options_execution_orders o
  LEFT JOIN public.dd_options_execution_fills f ON f.order_attempt_id = o.id
  WHERE o.group_id = v_order.group_id AND o.leg_id = v_order.leg_id;

  IF v_leg_exit_qty > v_leg_entry_qty OR
     v_leg_entry_qty > (SELECT requested_qty FROM public.dd_options_execution_legs WHERE id = v_order.leg_id) OR
     v_leg_entry_currency_count > 1 OR v_leg_exit_currency_count > 1 THEN
    v_reconciliation_required := TRUE;
  END IF;

  UPDATE public.dd_options_execution_legs
  SET filled_qty = v_leg_entry_qty,
      average_fill_price = v_leg_entry_avg,
      commission = v_leg_entry_commission,
      commission_currency = v_leg_entry_currency,
      exit_filled_qty = v_leg_exit_qty,
      exit_average_fill_price = v_leg_exit_avg,
      exit_commission = v_leg_exit_commission,
      exit_commission_currency = v_leg_exit_currency,
      order_state = CASE
        WHEN v_reconciliation_required THEN 'RECONCILIATION_REQUIRED'
        WHEN v_leg_entry_qty > 0 AND v_leg_exit_qty >= v_leg_entry_qty THEN 'CLOSED'
        WHEN v_leg_exit_qty > 0 THEN 'CLOSING'
        WHEN v_leg_entry_qty >= requested_qty THEN 'FILLED'
        WHEN v_leg_entry_qty > 0 THEN 'PARTIALLY_FILLED'
        ELSE order_state
      END,
      updated_at = NOW()
  WHERE id = v_order.leg_id;

  IF v_reconciliation_required THEN
    UPDATE public.dd_options_execution_groups
    SET state = 'RECONCILIATION_REQUIRED',
        last_error_code = 'OPTIONS_FILL_RECONCILIATION_REQUIRED',
        last_error_detail = 'Exchange fill quantities or commission currencies require review',
        updated_at = NOW()
    WHERE id = v_order.group_id;
  END IF;

  RETURN jsonb_build_object(
    'duplicate', false,
    'fill_id', v_fill_id,
    'order_attempt_id', v_order.id,
    'group_id', v_order.group_id,
    'leg_id', v_order.leg_id,
    'order_filled_qty', v_total_qty,
    'leg_entry_qty', v_leg_entry_qty,
    'leg_exit_qty', v_leg_exit_qty,
    'reconciliation_required', v_reconciliation_required
  );
END;
$;

