-- Atomic reservation: the active-slot unique index, group and all leg rows are
-- committed in one database transaction before any exchange order is eligible.
CREATE OR REPLACE FUNCTION public.reserve_dd_options_execution_group(
  p_group JSONB,
  p_legs JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  v_group_id UUID;
  v_client_group_id TEXT;
  v_strategy TEXT;
  v_underlying TEXT;
  v_direction TEXT;
  v_option_type TEXT;
  v_expiry TIMESTAMPTZ;
  v_qty INTEGER;
  v_risk_budget NUMERIC;
  v_max_loss NUMERIC;
  v_reserved_margin NUMERIC;
  v_net_credit NUMERIC;
  v_leg_count INTEGER;
  v_wing JSONB;
  v_short JSONB;
  v_leg JSONB;
  v_role TEXT;
  v_side TEXT;
  v_leg_qty INTEGER;
  v_leg_expiry TIMESTAMPTZ;
  v_contract_type TEXT;
  v_leg_option_type TEXT;
  v_contract_value NUMERIC;
  v_tick_size NUMERIC;
  v_strike NUMERIC;
  v_symbol_parts TEXT[];
  v_expected_expiry TIMESTAMPTZ;
  v_symbol TEXT;
BEGIN
  IF jsonb_typeof(p_group) IS DISTINCT FROM 'object' OR
     jsonb_typeof(p_legs) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Options reservation requires a group object and leg array';
  END IF;

  v_client_group_id := NULLIF(BTRIM(p_group->>'client_group_id'), '');
  v_strategy := UPPER(COALESCE(p_group->>'strategy', ''));
  v_underlying := UPPER(COALESCE(p_group->>'underlying_symbol', ''));
  v_direction := UPPER(COALESCE(p_group->>'underlying_direction', ''));
  v_option_type := UPPER(COALESCE(p_group->>'option_type', ''));
  v_expiry := NULLIF(p_group->>'expiry_at', '')::TIMESTAMPTZ;
  v_qty := NULLIF(p_group->>'requested_qty', '')::INTEGER;
  v_risk_budget := NULLIF(p_group->>'risk_budget_usd', '')::NUMERIC;
  v_max_loss := NULLIF(p_group->>'max_loss_usd', '')::NUMERIC;
  v_reserved_margin := COALESCE(NULLIF(p_group->>'reserved_margin_usd', '')::NUMERIC, 0);
  v_net_credit := NULLIF(p_group->>'net_credit_usd', '')::NUMERIC;
  v_leg_count := jsonb_array_length(p_legs);

  IF v_client_group_id IS NULL OR LENGTH(v_client_group_id) > 80 THEN
    RAISE EXCEPTION 'Options reservation requires a valid client group ID';
  END IF;
  IF v_strategy NOT IN ('OPTIONS_BUY', 'OPTIONS_SELL') THEN
    RAISE EXCEPTION 'Unsupported Options strategy';
  END IF;
  IF v_underlying NOT IN ('BTCUSD', 'ETHUSD') THEN
    RAISE EXCEPTION 'Automated Options entries are restricted to BTCUSD and ETHUSD';
  END IF;
  IF v_direction NOT IN ('BUY', 'SELL') OR v_option_type NOT IN ('CALL', 'PUT') THEN
    RAISE EXCEPTION 'Options direction and type are invalid';
  END IF;
  IF v_expiry IS NULL OR v_expiry <= NOW() OR
     v_qty IS NULL OR v_qty < 1 OR
     v_risk_budget IS NULL OR v_risk_budget <= 0 OR
     v_max_loss IS NULL OR v_max_loss <= 0 OR
     v_max_loss > v_risk_budget OR
     v_reserved_margin <= 0 THEN
    RAISE EXCEPTION 'Options risk, size, margin or expiry inputs are missing/out of bounds';
  END IF;

  IF v_strategy = 'OPTIONS_BUY' THEN
    IF v_leg_count <> 1 OR
       NOT ((v_direction = 'BUY' AND v_option_type = 'CALL') OR
            (v_direction = 'SELL' AND v_option_type = 'PUT')) THEN
      RAISE EXCEPTION 'Long Options strategy must be one direction-matched CALL/PUT BUY';
    END IF;
    IF UPPER(COALESCE(p_legs->0->>'role', '')) <> 'LONG_PREMIUM' OR
       UPPER(COALESCE(p_legs->0->>'side', '')) <> 'BUY' THEN
      RAISE EXCEPTION 'Long Options entry cannot contain a short leg';
    END IF;
  ELSE
    IF v_leg_count <> 2 OR v_net_credit IS NULL OR v_net_credit <= 0 OR
       NOT ((v_direction = 'BUY' AND v_option_type = 'PUT') OR
            (v_direction = 'SELL' AND v_option_type = 'CALL')) THEN
      RAISE EXCEPTION 'Credit spread requires positive net credit and a direction-matched same-type pair';
    END IF;

    SELECT x.element INTO v_wing
    FROM jsonb_array_elements(p_legs) AS x(element)
    WHERE UPPER(COALESCE(x.element->>'role', '')) = 'PROTECTIVE_WING';
    SELECT x.element INTO v_short
    FROM jsonb_array_elements(p_legs) AS x(element)
    WHERE UPPER(COALESCE(x.element->>'role', '')) = 'SHORT_OPTION';

    IF v_wing IS NULL OR v_short IS NULL OR
       UPPER(COALESCE(v_wing->>'side', '')) <> 'BUY' OR
       UPPER(COALESCE(v_short->>'side', '')) <> 'SELL' THEN
      RAISE EXCEPTION 'Credit spread requires one protective BUY and one short SELL';
    END IF;
    IF UPPER(COALESCE(v_wing->>'optionType', '')) <> v_option_type OR
       UPPER(COALESCE(v_short->>'optionType', '')) <> v_option_type OR
       NULLIF(v_wing->>'expiry_at', '')::TIMESTAMPTZ IS DISTINCT FROM
         NULLIF(v_short->>'expiry_at', '')::TIMESTAMPTZ OR
       NULLIF(v_wing->>'qty', '')::INTEGER IS DISTINCT FROM v_qty OR
       NULLIF(v_short->>'qty', '')::INTEGER IS DISTINCT FROM v_qty OR
       NULLIF(v_wing->>'contractValue', '')::NUMERIC IS DISTINCT FROM
         NULLIF(v_short->>'contractValue', '')::NUMERIC THEN
      RAISE EXCEPTION 'Credit spread legs must match type, expiry, quantity and contract multiplier';
    END IF;
    IF (v_option_type = 'PUT' AND
        NULLIF(v_wing->>'strike', '')::NUMERIC >= NULLIF(v_short->>'strike', '')::NUMERIC) OR
       (v_option_type = 'CALL' AND
        NULLIF(v_wing->>'strike', '')::NUMERIC <= NULLIF(v_short->>'strike', '')::NUMERIC) THEN
      RAISE EXCEPTION 'Credit spread protective wing must be farther out of the money';
    END IF;
  END IF;

  FOR v_leg IN
    SELECT x.element FROM jsonb_array_elements(p_legs) AS x(element)
  LOOP
    v_role := UPPER(COALESCE(v_leg->>'role', ''));
    v_side := UPPER(COALESCE(v_leg->>'side', ''));
    v_leg_qty := NULLIF(v_leg->>'qty', '')::INTEGER;
    v_leg_expiry := NULLIF(v_leg->>'expiry_at', '')::TIMESTAMPTZ;
    v_contract_type := LOWER(COALESCE(v_leg->>'contractType', ''));
    v_leg_option_type := UPPER(COALESCE(v_leg->>'optionType', ''));
    v_contract_value := NULLIF(v_leg->>'contractValue', '')::NUMERIC;
    v_tick_size := NULLIF(v_leg->>'tickSize', '')::NUMERIC;
    v_strike := NULLIF(v_leg->>'strike', '')::NUMERIC;
    v_symbol := UPPER(COALESCE(v_leg->>'symbol', ''));
    v_symbol_parts := regexp_match(v_symbol, '^([CP])-(BTC|ETH)-([0-9]+)-([0-9]{6})$');

    IF v_role NOT IN ('LONG_PREMIUM', 'PROTECTIVE_WING', 'SHORT_OPTION') OR
       v_side NOT IN ('BUY', 'SELL') OR
       v_leg_qty IS DISTINCT FROM v_qty OR
       v_leg_expiry IS DISTINCT FROM v_expiry OR
       v_leg_option_type IS DISTINCT FROM v_option_type OR
       v_contract_type NOT IN ('call_options', 'put_options') OR
       (v_leg_option_type = 'CALL' AND v_contract_type <> 'call_options') OR
       (v_leg_option_type = 'PUT' AND v_contract_type <> 'put_options') OR
       COALESCE(NULLIF(v_leg->>'productId', '')::INTEGER, 0) <= 0 OR
       v_contract_value IS NULL OR v_contract_value <= 0 OR
       v_tick_size IS NULL OR v_tick_size <= 0 OR
       v_strike IS NULL OR v_strike <= 0 OR
       NULLIF(BTRIM(v_leg->>'clientOrderId'), '') IS NULL OR
       LENGTH(v_leg->>'clientOrderId') > 32 OR
       v_symbol_parts IS NULL THEN
      RAISE EXCEPTION 'Options reservation contains an invalid contract leg';
    END IF;

    IF v_symbol_parts[1] <> CASE WHEN v_leg_option_type = 'CALL' THEN 'C' ELSE 'P' END OR
       v_symbol_parts[2] <> CASE WHEN v_underlying = 'BTCUSD' THEN 'BTC' ELSE 'ETH' END OR
       v_symbol_parts[3]::NUMERIC <> v_strike THEN
      RAISE EXCEPTION 'Options leg symbol does not match its product type, underlying or strike';
    END IF;

    v_expected_expiry :=
      (TO_DATE(v_symbol_parts[4], 'DDMMYY')::TIMESTAMP + INTERVAL '12 hours') AT TIME ZONE 'UTC';
    IF v_expected_expiry IS DISTINCT FROM v_expiry THEN
      RAISE EXCEPTION 'Options leg symbol expiry does not match its verified settlement timestamp';
    END IF;
  END LOOP;

  INSERT INTO public.dd_options_execution_groups (
    client_group_id, strategy, state, underlying_symbol, underlying_direction,
    option_type, expiry_at, requested_qty, matched_qty, risk_budget_usd,
    max_loss_usd, reserved_margin_usd, net_credit_usd, raw
  ) VALUES (
    v_client_group_id, v_strategy, 'RESERVED', v_underlying, v_direction,
    v_option_type, v_expiry, v_qty, 0, v_risk_budget, v_max_loss,
    v_reserved_margin, v_net_credit, COALESCE(p_group->'raw', p_group)
  ) RETURNING id INTO v_group_id;

  INSERT INTO public.dd_options_execution_legs (
    group_id, leg_role, product_id, symbol, contract_type, option_type,
    strike, contract_value, tick_size, expiry_at, side, requested_qty,
    filled_qty, order_state, client_order_id, raw
  )
  SELECT
    v_group_id,
    UPPER(x.element->>'role'),
    (x.element->>'productId')::INTEGER,
    UPPER(x.element->>'symbol'),
    LOWER(x.element->>'contractType'),
    UPPER(x.element->>'optionType'),
    (x.element->>'strike')::NUMERIC,
    (x.element->>'contractValue')::NUMERIC,
    (x.element->>'tickSize')::NUMERIC,
    (x.element->>'expiry_at')::TIMESTAMPTZ,
    UPPER(x.element->>'side'),
    (x.element->>'qty')::INTEGER,
    0,
    'RESERVED',
    x.element->>'clientOrderId',
    x.element
  FROM jsonb_array_elements(p_legs) AS x(element);

  RETURN jsonb_build_object(
    'group_id', v_group_id,
    'client_group_id', v_client_group_id,
    'state', 'RESERVED',
    'leg_count', v_leg_count
  );
END;
$$;

REVOKE ALL ON FUNCTION public.reserve_dd_options_execution_group(JSONB, JSONB) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.reserve_dd_options_execution_group(JSONB, JSONB) TO service_role;


-- Persist an idempotent IOC attempt before any exchange request. Side and
-- quantity are derived in the database from the reserved group and leg state.
CREATE OR REPLACE FUNCTION public.reserve_dd_options_order_attempt(
  p_group_id UUID,
  p_leg_role TEXT,
  p_intent TEXT,
  p_attempt_no INTEGER,
  p_client_order_id TEXT,
  p_limit_price NUMERIC
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $
DECLARE
  v_group public.dd_options_execution_groups%ROWTYPE;
  v_leg public.dd_options_execution_legs%ROWTYPE;
  v_protective public.dd_options_execution_legs%ROWTYPE;
  v_short public.dd_options_execution_legs%ROWTYPE;
  v_role TEXT;
  v_intent TEXT;
  v_side TEXT;
  v_qty NUMERIC;
  v_reduce_only BOOLEAN;
  v_previous_attempt INTEGER;
  v_pending_count INTEGER;
  v_order public.dd_options_execution_orders%ROWTYPE;
  v_next_group_state TEXT;
BEGIN
  v_role := UPPER(COALESCE(p_leg_role, ''));
  v_intent := UPPER(COALESCE(p_intent, ''));

  IF p_group_id IS NULL OR
     v_role NOT IN ('LONG_PREMIUM', 'PROTECTIVE_WING', 'SHORT_OPTION') OR
     v_intent NOT IN ('ENTRY', 'EXIT', 'UNWIND') OR
     p_attempt_no IS NULL OR p_attempt_no < 1 OR
     NULLIF(BTRIM(p_client_order_id), '') IS NULL OR LENGTH(p_client_order_id) > 32 OR
     p_limit_price IS NULL OR p_limit_price <= 0 THEN
    RAISE EXCEPTION 'Options order attempt inputs are invalid';
  END IF;

  SELECT * INTO v_group
  FROM public.dd_options_execution_groups
  WHERE id = p_group_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Options execution group does not exist';
  END IF;
  IF v_group.state IN ('CLOSED', 'REJECTED', 'FAILED', 'RECONCILIATION_REQUIRED') THEN
    RAISE EXCEPTION 'Options group is terminal or reconciliation-locked';
  END IF;

  SELECT * INTO v_leg
  FROM public.dd_options_execution_legs
  WHERE group_id = p_group_id AND leg_role = v_role
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Options execution leg does not exist in this group';
  END IF;

  SELECT COALESCE(MAX(attempt_no), 0) INTO v_previous_attempt
  FROM public.dd_options_execution_orders
  WHERE group_id = p_group_id AND leg_role = v_role AND intent = v_intent;
  IF p_attempt_no <> v_previous_attempt + 1 THEN
    RAISE EXCEPTION 'Options order attempt number is not the next idempotent sequence';
  END IF;

  SELECT COUNT(*) INTO v_pending_count
  FROM public.dd_options_execution_orders
  WHERE group_id = p_group_id
    AND leg_role = v_role
    AND intent = v_intent
    AND order_state IN ('RESERVED', 'SUBMITTED', 'OPEN', 'PARTIALLY_FILLED', 'UNKNOWN', 'RECONCILIATION_REQUIRED');
  IF v_pending_count > 0 THEN
    RAISE EXCEPTION 'An unresolved Options order attempt already exists for this leg and intent';
  END IF;

  IF v_intent = 'ENTRY' THEN
    IF v_group.expiry_at <= NOW() OR v_leg.filled_qty >= v_leg.requested_qty THEN
      RAISE EXCEPTION 'Options entry is expired or fully filled';
    END IF;
    IF v_group.strategy = 'OPTIONS_BUY' THEN
      IF v_role <> 'LONG_PREMIUM' OR v_leg.side <> 'BUY' THEN
        RAISE EXCEPTION 'Long Options entry permits only the direction-matched premium BUY leg';
      END IF;
    ELSE
      IF v_role = 'LONG_PREMIUM' THEN
        RAISE EXCEPTION 'Credit spread cannot contain a long-premium single-leg entry';
      ELSIF v_role = 'PROTECTIVE_WING' THEN
        IF v_leg.side <> 'BUY' THEN
          RAISE EXCEPTION 'Credit spread protective wing must be a BUY';
        END IF;
      ELSIF v_role = 'SHORT_OPTION' THEN
        SELECT * INTO v_protective
        FROM public.dd_options_execution_legs
        WHERE group_id = p_group_id AND leg_role = 'PROTECTIVE_WING'
        FOR UPDATE;
        IF NOT FOUND OR v_protective.order_state NOT IN ('FILLED', 'PARTIALLY_FILLED') OR
           v_protective.filled_qty <= v_protective.exit_filled_qty THEN
          RAISE EXCEPTION 'Protective wing must have confirmed entry fills before short SELL';
        END IF;
        IF v_leg.side <> 'SELL' THEN
          RAISE EXCEPTION 'Credit spread short option leg must be SELL';
        END IF;
      END IF;
    END IF;

    IF v_role = 'SHORT_OPTION' THEN
      v_qty := LEAST(
        v_leg.requested_qty - v_leg.filled_qty,
        v_protective.filled_qty - v_protective.exit_filled_qty - v_leg.filled_qty
      );
    ELSE
      v_qty := v_leg.requested_qty - v_leg.filled_qty;
    END IF;
    IF v_qty <= 0 THEN
      RAISE EXCEPTION 'No unmatched exchange-confirmed quantity is eligible for entry';
    END IF;
    v_side := v_leg.side;
    v_reduce_only := FALSE;
    v_next_group_state := CASE v_role
      WHEN 'LONG_PREMIUM' THEN 'BUY_ENTRY_PENDING'
      WHEN 'PROTECTIVE_WING' THEN 'HEDGE_ENTRY_PENDING'
      ELSE 'SHORT_ENTRY_PENDING'
    END;
  ELSIF v_intent = 'EXIT' THEN
    v_reduce_only := TRUE;
    IF v_role = 'SHORT_OPTION' THEN
      IF v_group.strategy <> 'OPTIONS_SELL' THEN
        RAISE EXCEPTION 'Only a credit spread has a short option exit leg';
      END IF;
    ELSIF v_role = 'PROTECTIVE_WING' THEN
      IF v_group.strategy <> 'OPTIONS_SELL' THEN
        RAISE EXCEPTION 'Protective wing exit is valid only for a credit spread';
      END IF;
      SELECT * INTO v_short
      FROM public.dd_options_execution_legs
      WHERE group_id = p_group_id AND leg_role = 'SHORT_OPTION'
      FOR UPDATE;
      IF FOUND AND v_short.filled_qty - v_short.exit_filled_qty > 0 THEN
        RAISE EXCEPTION 'Short option must be exchange-confirmed flat before protective wing exit';
      END IF;
    ELSIF v_role = 'LONG_PREMIUM' AND v_group.strategy <> 'OPTIONS_BUY' THEN
      RAISE EXCEPTION 'A credit spread cannot be exited through the long-premium role';
    END IF;

    v_qty := v_leg.filled_qty - v_leg.exit_filled_qty;
    IF v_qty <= 0 THEN
      RAISE EXCEPTION 'No exchange-confirmed open Options quantity remains to exit';
    END IF;
    v_side := CASE v_leg.side WHEN 'BUY' THEN 'SELL' ELSE 'BUY' END;
    v_next_group_state := CASE v_role
      WHEN 'LONG_PREMIUM' THEN 'LONG_EXIT_PENDING'
      WHEN 'SHORT_OPTION' THEN 'SHORT_EXIT_PENDING'
      ELSE 'HEDGE_EXIT_PENDING'
    END;
  ELSE
    IF v_group.strategy <> 'OPTIONS_SELL' OR v_role <> 'PROTECTIVE_WING' OR
       v_group.state NOT IN ('SHORT_ENTRY_PENDING', 'UNWIND_PENDING') THEN
      RAISE EXCEPTION 'Only a protective wing during failed/partial short entry may be unwound';
    END IF;
    SELECT * INTO v_short
    FROM public.dd_options_execution_legs
    WHERE group_id = p_group_id AND leg_role = 'SHORT_OPTION'
    FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Credit spread short leg is missing during unwind';
    END IF;
    SELECT COUNT(*) INTO v_pending_count
    FROM public.dd_options_execution_orders
    WHERE group_id = p_group_id AND leg_role = 'SHORT_OPTION' AND intent = 'ENTRY'
      AND order_state IN ('RESERVED', 'SUBMITTED', 'OPEN', 'PARTIALLY_FILLED', 'UNKNOWN', 'RECONCILIATION_REQUIRED');
    IF v_pending_count > 0 THEN
      RAISE EXCEPTION 'Short leg entry must be terminal and reconciled before protective unwind';
    END IF;
    v_qty := v_leg.filled_qty - v_leg.exit_filled_qty -
      GREATEST(0, v_short.filled_qty - v_short.exit_filled_qty);
    IF v_qty <= 0 THEN
      RAISE EXCEPTION 'No unmatched protective wing quantity is eligible for unwind';
    END IF;
    v_side := 'SELL';
    v_reduce_only := TRUE;
    v_next_group_state := 'UNWIND_PENDING';
  END IF;

  IF ABS((p_limit_price / v_leg.tick_size) - ROUND(p_limit_price / v_leg.tick_size)) > 0.00000001 THEN
    RAISE EXCEPTION 'Options limit price is not aligned to the stored Testnet tick size';
  END IF;

  INSERT INTO public.dd_options_execution_orders (
    group_id, leg_id, leg_role, intent, attempt_no, product_id, symbol,
    side, requested_qty, filled_qty, limit_price, reduce_only, order_state,
    client_order_id, raw
  ) VALUES (
    p_group_id, v_leg.id, v_role, v_intent, p_attempt_no, v_leg.product_id,
    v_leg.symbol, v_side, v_qty, 0, p_limit_price, v_reduce_only, 'RESERVED',
    p_client_order_id,
    jsonb_build_object('reservation', true, 'derived_side', v_side, 'derived_qty', v_qty)
  )
  RETURNING * INTO v_order;

  UPDATE public.dd_options_execution_groups
  SET state = v_next_group_state, updated_at = NOW()
  WHERE id = p_group_id;

  RETURN jsonb_build_object(
    'order_attempt_id', v_order.id,
    'group_id', p_group_id,
    'leg_id', v_leg.id,
    'leg_role', v_role,
    'intent', v_intent,
    'attempt_no', p_attempt_no,
    'product_id', v_leg.product_id,
    'symbol', v_leg.symbol,
    'side', v_side,
    'qty', v_qty,
    'limit_price', p_limit_price,
    'reduce_only', v_reduce_only,
    'client_order_id', p_client_order_id,
    'order_state', 'RESERVED'
  );
END;
$;

