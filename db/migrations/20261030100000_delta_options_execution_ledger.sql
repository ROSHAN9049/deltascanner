CREATE OR REPLACE FUNCTION public.record_dd_options_order_ack(
  p_order_attempt_id BIGINT,
  p_exchange_order_id TEXT,
  p_order_state TEXT,
  p_ack_filled_qty NUMERIC,
  p_ack_average_fill_price NUMERIC,
  p_raw JSONB DEFAULT '{}'::JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $
DECLARE
  v_order public.dd_options_execution_orders%ROWTYPE;
  v_state TEXT;
  v_reconciliation_required BOOLEAN := FALSE;
BEGIN
  v_state := UPPER(COALESCE(p_order_state, 'UNKNOWN'));
  IF p_order_attempt_id IS NULL OR v_state NOT IN (
    'RESERVED', 'SUBMITTED', 'OPEN', 'PARTIALLY_FILLED', 'FILLED',
    'CANCELLED', 'REJECTED', 'UNKNOWN', 'RECONCILIATION_REQUIRED'
  ) OR p_ack_filled_qty IS NULL OR p_ack_filled_qty < 0 OR
     (p_ack_average_fill_price IS NOT NULL AND p_ack_average_fill_price <= 0) THEN
    RAISE EXCEPTION 'Options order acknowledgement fields are invalid';
  END IF;

  SELECT * INTO v_order
  FROM public.dd_options_execution_orders
  WHERE id = p_order_attempt_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Options order attempt does not exist';
  END IF;

  IF p_ack_filled_qty > v_order.requested_qty OR
     (v_state = 'FILLED' AND p_ack_filled_qty <> v_order.requested_qty) OR
     p_ack_filled_qty < v_order.filled_qty OR
     v_state IN ('UNKNOWN', 'RECONCILIATION_REQUIRED') THEN
    v_reconciliation_required := TRUE;
    v_state := 'RECONCILIATION_REQUIRED';
  END IF;

  UPDATE public.dd_options_execution_orders
  SET exchange_order_id = COALESCE(p_exchange_order_id, exchange_order_id),
      acknowledged_filled_qty = p_ack_filled_qty,
      acknowledged_at = NOW(),
      order_state = v_state,
      raw = COALESCE(raw, '{}'::JSONB) || COALESCE(p_raw, '{}'::JSONB) ||
        jsonb_build_object('acknowledged_state', p_order_state, 'acknowledged_filled_qty', p_ack_filled_qty),
      updated_at = NOW()
  WHERE id = p_order_attempt_id;

  IF v_reconciliation_required THEN
    UPDATE public.dd_options_execution_groups
    SET state = 'RECONCILIATION_REQUIRED',
        last_error_code = 'OPTIONS_ORDER_ACK_MISMATCH',
        last_error_detail = 'Exchange order acknowledgement requires fill reconciliation',
        updated_at = NOW()
    WHERE id = v_order.group_id;
  END IF;

  RETURN jsonb_build_object(
    'order_attempt_id', p_order_attempt_id,
    'exchange_order_id', p_exchange_order_id,
    'order_state', v_state,
    'acknowledged_filled_qty', p_ack_filled_qty,
    'reconciliation_required', v_reconciliation_required
  );
END;
$;

