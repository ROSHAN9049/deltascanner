-- Options use a separate ledger from dd_delta_positions so the perpetual-only
-- futures reconciler cannot close or hydrate option legs as Futures positions.
CREATE TABLE IF NOT EXISTS public.dd_options_execution_groups (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  client_group_id TEXT NOT NULL UNIQUE,
  execution_slot TEXT NOT NULL DEFAULT 'DELTA_TESTNET_OPTIONS',
  strategy TEXT NOT NULL CHECK (strategy IN ('OPTIONS_BUY', 'OPTIONS_SELL')),
  state TEXT NOT NULL CHECK (state IN (
    'RESERVED',
    'BUY_ENTRY_PENDING',
    'HEDGE_ENTRY_PENDING',
    'SHORT_ENTRY_PENDING',
    'OPEN',
    'LONG_EXIT_PENDING',
    'SHORT_EXIT_PENDING',
    'HEDGE_EXIT_PENDING',
    'UNWIND_PENDING',
    'RECONCILIATION_REQUIRED',
    'CLOSED',
    'REJECTED',
    'FAILED'
  )),
  underlying_symbol TEXT NOT NULL CHECK (underlying_symbol IN ('BTCUSD', 'ETHUSD')),
  underlying_direction TEXT NOT NULL CHECK (underlying_direction IN ('BUY', 'SELL')),
  option_type TEXT NOT NULL CHECK (option_type IN ('CALL', 'PUT')),
  expiry_at TIMESTAMPTZ NOT NULL,
  requested_qty INTEGER NOT NULL CHECK (requested_qty > 0),
  matched_qty INTEGER NOT NULL DEFAULT 0 CHECK (matched_qty >= 0),
  risk_budget_usd NUMERIC NOT NULL CHECK (risk_budget_usd >= 0),
  max_loss_usd NUMERIC NOT NULL CHECK (max_loss_usd >= 0),
  reserved_margin_usd NUMERIC NOT NULL DEFAULT 0 CHECK (reserved_margin_usd >= 0),
  net_credit_usd NUMERIC NULL,
  last_error_code TEXT NULL,
  last_error_detail TEXT NULL,
  raw JSONB NOT NULL DEFAULT '{}'::JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  closed_at TIMESTAMPTZ NULL,
  CHECK (matched_qty <= requested_qty)
